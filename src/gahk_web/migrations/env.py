"""Alembic's environment for gahk_web: where a migration run gets its database connection.

Two ways in:
- db.migrate() (the updater's `python -m gahk_web migrate`, the devserver, the tests) hands its
  connection over in config.attributes["connection"]: no Flask, no alembic.ini lookup by the
  current directory, no logging setup.
- Flask-Migrate's `flask db ...` (task migration, task migration:check) runs inside the dev app's
  context and takes a connection from Flask-SQLAlchemy's engine.

Each revision runs in a transaction of its own. A new revision gets the next number (0002, 0003, ...)
instead of Alembic's random id, and an autogenerated one with no changes is not written at all.
"""

from collections.abc import Collection, Mapping
from typing import Any

from alembic import context
from alembic.operations.ops import MigrationScript
from alembic.runtime.migration import MigrationContext, MigrationInfo
from alembic.script import ScriptDirectory
from sqlalchemy.engine import Connection

from gahk_web.models import Base


def next_revision_id() -> str:
    script = ScriptDirectory.from_config(context.config)
    numbers = [int(rev.revision) for rev in script.walk_revisions() if rev.revision.isdigit()]
    return f"{max(numbers, default=0) + 1:04d}"


def process_revision_directives(
    migration_context: MigrationContext,
    revision: Any,  # noqa: ANN401 - Alembic's
    directives: list[MigrationScript],
) -> None:
    script = directives[0]
    if getattr(context.config.cmd_opts, "autogenerate", False) and script.upgrade_ops is not None:
        if script.upgrade_ops.is_empty():
            directives[:] = []
            print("The models and the migrations agree: no revision written.")
            return
    script.rev_id = next_revision_id()


def record_applied(
    ctx: MigrationContext, step: MigrationInfo, heads: Collection[Any], run_args: Mapping[str, Any]
) -> None:
    applied = context.config.attributes.get("applied")
    if applied is not None and step.is_upgrade:
        applied.append(step.up_revision_id)


def run(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=Base.metadata,
        compare_server_default=True,
        transaction_per_migration=True,
        process_revision_directives=process_revision_directives,
        on_version_apply=record_applied,
    )
    with context.begin_transaction():
        context.run_migrations()


if context.is_offline_mode():
    raise SystemExit("gahk_web's migrations run against a database; --sql is not supported")

given: Connection | None = context.config.attributes.get("connection")
if given is not None:
    run(given)
else:
    from flask import current_app

    with current_app.extensions["sqlalchemy"].engine.connect() as connection:
        run(connection)
